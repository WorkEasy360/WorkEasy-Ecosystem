// @vitest-environment node
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import {
  missingRoutes,
  pageRoutesOnDisk,
  parseAppRoutes,
  routeForSegments,
} from "./route-guard.mjs";

describe("routeForSegments", () => {
  it("spells routes the way Next.js lists them in AppRoutes", () => {
    expect(routeForSegments([])).toBe("/");
    expect(routeForSegments(["o", "[orgSlug]", "dashboard"])).toBe("/o/[orgSlug]/dashboard");
    expect(routeForSegments(["(site)", "products", "[slug]"])).toBe("/products/[slug]");
  });

  it("leaves out folders Next.js does not route on their own", () => {
    expect(routeForSegments(["o", "_components"])).toBeNull();
    expect(routeForSegments(["feed", "@modal"])).toBeNull();
    expect(routeForSegments(["feed", "(..)photo", "[id]"])).toBeNull();
  });
});

describe("pageRoutesOnDisk", () => {
  let appDir;

  afterEach(() => {
    rmSync(appDir, { recursive: true, force: true });
  });

  it("finds every page file and nothing else", () => {
    appDir = mkdtempSync(join(tmpdir(), "route-guard-"));
    for (const file of [
      "page.tsx",
      "o/[orgSlug]/layout.tsx",
      "o/[orgSlug]/page.tsx",
      "o/[orgSlug]/dashboard/page.tsx",
      "o/[orgSlug]/settings/security/network/page.tsx",
      "(site)/pricing/page.tsx",
      "_lib/page.tsx",
      "api/health/route.ts",
    ]) {
      const path = join(appDir, file);
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, "");
    }

    expect([...pageRoutesOnDisk(appDir)].sort()).toEqual([
      "/",
      "/o/[orgSlug]",
      "/o/[orgSlug]/dashboard",
      "/o/[orgSlug]/settings/security/network",
      "/pricing",
    ]);
  });
});

describe("parseAppRoutes", () => {
  it("reads the AppRoutes union of a generated routes.d.ts", () => {
    const routesDts = [
      "// This file is generated automatically by Next.js",
      "// Do not edit this file manually",
      "",
      'type AppRoutes = "/" | "/o/[orgSlug]" | "/partner/[partnerId]"',
      "type PageRoutes = never",
      'type LayoutRoutes = "/" | "/o/[orgSlug]"',
    ].join("\r\n");

    expect([...parseAppRoutes(routesDts)]).toEqual(["/", "/o/[orgSlug]", "/partner/[partnerId]"]);
  });

  it("reads an app with no pages as an empty set", () => {
    expect(parseAppRoutes("type AppRoutes = never").size).toBe(0);
  });

  it("returns null for a file it does not recognise", () => {
    expect(parseAppRoutes("export type Routes = string")).toBeNull();
  });
});

describe("missingRoutes", () => {
  it("lists routes on disk the server does not know, and ignores extra ones it does", () => {
    const onDisk = new Set(["/", "/o/[orgSlug]", "/o/[orgSlug]/dashboard", "/admin/users/[userId]"]);
    const known = new Set(["/", "/o/[orgSlug]", "/deleted-a-moment-ago"]);

    expect(missingRoutes(onDisk, known)).toEqual(["/admin/users/[userId]", "/o/[orgSlug]/dashboard"]);
  });
});
